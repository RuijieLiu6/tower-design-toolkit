"""Build src/data/evidence_index.json for the Sources & assumptions hub (research P16-M01).

Reads the latest round of every research packet (04 Tool Plan/research/{modules,modules-completion,context-model}/<id>/)
and writes:
  - sources: research metadata (title, publisher, year, type, opened, source ids) for every URL the app's code cites;
  - falseAssumptions: every FALSE_ASSUMPTION flag with its claim and correction, by packet.
Run:  python -I tools/build_evidence_index.py   (from tower-studio/). Deterministic: sorted keys, no timestamps.
"""
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
RESEARCH = os.path.join(os.path.dirname(APP), '04 Tool Plan', 'research')
SRC = os.path.join(APP, 'src')
OUT = os.path.join(SRC, 'data', 'evidence_index.json')


def norm(url: str) -> str:
    u = url.strip().split('#')[0].rstrip('/')
    m = re.match(r'^(https?)://([^/]+)(.*)$', u, re.I)
    return f"{m.group(1).lower()}://{m.group(2).lower()}{m.group(3)}" if m else u


def latest(folder: str):
    revs = glob.glob(os.path.join(folder, 'revise-r*_*.json'))
    if revs:
        return max(revs, key=lambda f: int(re.search(r'revise-r(\d+)', f).group(1)))
    first = glob.glob(os.path.join(folder, 'research_*.json'))
    return first[0] if first else None


def app_ids() -> set:
    ids = set()
    for root, _, files in os.walk(SRC):
        for fn in files:
            if fn.endswith(('.ts', '.tsx')) and '.test.' not in fn:
                ids.update(re.findall(r'\b[PC]\d{2}-S\d+\b', open(os.path.join(root, fn), encoding='utf-8').read()))
    return ids


def app_urls() -> set:
    urls = set()
    for root, _, files in os.walk(SRC):
        for fn in files:
            if fn.endswith(('.ts', '.tsx')) and '.test.' not in fn:
                text = open(os.path.join(root, fn), encoding='utf-8').read()
                for u in re.findall(r"https?://[^\s'\"`)]+", text):
                    urls.add(norm(u))
    return urls


def main() -> int:
    wanted = app_urls()
    wanted_ids = app_ids()
    by_id: dict = {}
    sources: dict = {}
    false: list = []
    seen_claims = set()
    for base in ('modules', 'modules-completion', 'context-model'):
        for folder in sorted(glob.glob(os.path.join(RESEARCH, base, '*'))):
            f = latest(folder) if os.path.isdir(folder) else None
            if not f:
                continue
            packet = os.path.basename(folder)
            rnd = re.search(r'revise-r(\d+)', f)
            data = json.load(open(f, encoding='utf-8'))
            for s in data.get('sources', []):
                # Research ids the app cites in text ("research P08-S57"): the latest stage wins (completion over modules).
                if s.get('id') in wanted_ids:
                    by_id[s['id']] = {'title': s.get('title', ''), 'publisher': s.get('publisher', ''), 'year': str(s.get('year', '')),
                                      'type': s.get('type', ''), 'opened': bool(s.get('opened')), 'url': s.get('url', ''), 'ids': [s['id']]}
                key = norm(s.get('url', ''))
                if key not in wanted:
                    continue
                e = sources.setdefault(key, {'title': s.get('title', ''), 'publisher': s.get('publisher', ''), 'year': str(s.get('year', '')),
                                            'type': s.get('type', ''), 'opened': False, 'ids': []})
                e['opened'] = e['opened'] or bool(s.get('opened'))
                if s.get('id') and s['id'] not in e['ids']:
                    e['ids'].append(s['id'])
            for x in data.get('flags', []):
                if x.get('type') != 'FALSE_ASSUMPTION' or not x.get('claim'):
                    continue
                k = (packet, x['claim'].strip())
                if k in seen_claims:
                    continue
                seen_claims.add(k)
                false.append({'packet': packet, 'claim': x['claim'].strip(), 'correction': (x.get('correction') or '').strip(),
                              'round': rnd.group(1) if rnd else '0', 'stage': base})
    for e in sources.values():
        e['ids'].sort()
    false.sort(key=lambda r: (r['packet'], r['claim']))
    out = {'note': 'Generated by tools/build_evidence_index.py from the research packets; do not edit by hand.',
           'sources': dict(sorted(sources.items())), 'byId': dict(sorted(by_id.items())), 'falseAssumptions': false}
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(out, fh, ensure_ascii=False, indent=1, sort_keys=False)
        fh.write('\n')
    print(f'{len(sources)} of {len(wanted)} cited URLs found in the research; {len(by_id)} of {len(wanted_ids)} cited research ids; {len(false)} false assumptions -> {OUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
