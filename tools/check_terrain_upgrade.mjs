import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
process.env.PLAYWRIGHT_BROWSERS_PATH = resolve('../tools-cache/ms-playwright')
const { chromium } = await import('playwright')
const out = resolve('../context-data/work/terrain-upgrade-2026-10-22')
mkdirSync(out, {recursive:true})
const browser = await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']})
const page = await browser.newPage({viewport:{width:1600,height:1000}})
page.setDefaultTimeout(30000)
const errors=[]; page.on('pageerror',e=>errors.push(e.message))
await page.goto('http://127.0.0.1:5202/#/start')
await page.getByRole('button',{name:'Open the demo project'}).click()
await page.waitForURL(/#\/guided/)
await page.evaluate(async()=>{
  const {useStore}=await import('/src/store.ts')
  useStore.getState().set({showOnboarding:false,reducedMotion:true})
  useStore.getState().setProject('city')
  useStore.getState().setEnabled([])
})
await page.getByText('Ground: City LiDAR 1 m where covered · Mountains: 30 m',{exact:true}).waitFor({timeout:60000})
await page.waitForTimeout(3500)
await page.screenshot({path:resolve(out,'vancouver-upgraded-overview.png')})
await page.evaluate(async()=>{
 const {useStore}=await import('/src/store.ts')
 useStore.getState().set({cameraRequest:{position:[-2000,-4000,1400],target:[0,14000,850],fov:60}})
})
await page.waitForTimeout(2000)
await page.screenshot({path:resolve(out,'vancouver-upgraded-mountains.png')})
await page.evaluate(async()=>{
 const {useStore}=await import('/src/store.ts')
 useStore.getState().updateTower('c1',{x:-800,y:800})
 useStore.getState().set({cameraRequest:{position:[-1800,-400,500],target:[-800,800,20],fov:55}})
})
await page.waitForTimeout(2000)
await page.screenshot({path:resolve(out,'vancouver-upgraded-ground.png')})
const sourceText=await page.locator('body').innerText()
if(!sourceText.includes('City LiDAR 2022 · 1 m ground'))throw new Error('Ground card did not report City LiDAR coverage')
console.log('Main view checked; releasing its WebGL context.')
await page.close()
const fallback = await browser.newPage({viewport:{width:1280,height:800}})
fallback.setDefaultTimeout(30000)
console.log('Testing missing mountain detail file.')
await fallback.route('**/data/terrain_r2_detail.bin',route=>route.abort('failed'))
await fallback.goto('http://127.0.0.1:5202/#/start')
await fallback.getByRole('button',{name:'Open the demo project'}).click()
await fallback.waitForURL(/#\/guided/)
await fallback.evaluate(async()=>{
 const {useStore}=await import('/src/store.ts');useStore.getState().set({showOnboarding:false,reducedMotion:true});useStore.getState().setProject('city');useStore.getState().setEnabled([])
})
await fallback.getByText('Ground: City LiDAR 1 m where covered · Mountains: 60 m',{exact:true}).waitFor({timeout:60000})
console.log('Fallback scene loaded.')
await fallback.locator('summary').filter({hasText:'Context layers'}).click()
await fallback.getByRole('alert').filter({hasText:'Some detailed context could not load'}).waitFor()
await fallback.screenshot({path:resolve(out,'vancouver-upgraded-fallback.png')})
const report={pageErrors:errors,groundSourceShown:true,detailedMountainGrid:30,failedMountainFileFallback:60}
writeFileSync(resolve(out,'browser-check.json'),JSON.stringify(report,null,2))
console.log(JSON.stringify(report));await browser.close()
if(errors.length)process.exitCode=1
