"""Copy the shareable parts of ../04 Tool Plan into docs/ for the public repository.

docs/ is generated: edit the originals in ../04 Tool Plan, then run
    python tools/sync_docs.py
Left out on purpose: permissions/ (draft messages to people), research/sources/ (verbatim
transcriptions of City documents), overnight/snapshots/ and test scratch folders.
"""
import shutil
import sys
from pathlib import Path

APP = Path(__file__).resolve().parents[1]
PLAN = APP.parent / "04 Tool Plan"
DOCS = APP / "docs"

INCLUDE = [
    "PLAN.md",
    "CONTEXT_MODEL_SPEC.md",
    "TERRAIN_UPGRADE_2026-10-22.md",
    "research",
    "evaluation",
    "mid-review",
    "city-requests",
    "renders",
    "tools",
    "overnight/BACKLOG.md",
    "overnight/DOWNLOADS.md",
    "overnight/MORNING_REPORT_2026-10-22.md",
    "overnight/QA.md",
    "overnight/a11y",
]
EXCLUDE_DIRS = {"sources", "snapshots", "node-builder-test", "__pycache__"}


def copy(src: Path, dst: Path) -> int:
    if src.is_file():
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        return 1
    n = 0
    for p in src.rglob("*"):
        rel = p.relative_to(src)
        if any(part in EXCLUDE_DIRS for part in rel.parts) or not p.is_file():
            continue
        n += copy(p, dst / rel)
    return n


def main() -> int:
    if not PLAN.is_dir():
        print(f"not found: {PLAN}", file=sys.stderr)
        return 1
    if DOCS.exists():
        shutil.rmtree(DOCS)
    total = 0
    for item in INCLUDE:
        src = PLAN / item
        if src.exists():
            total += copy(src, DOCS / item)
        else:
            print(f"skip (missing): {item}")
    (DOCS / "README.md").write_text(
        "# Project docs (generated)\n\n"
        "A copy of the shareable parts of the team's `04 Tool Plan` folder: plan and tracker, Context Model spec, "
        "research logs with sources and false assumptions, evaluation reports, mid-review drafts, City request drafts "
        "and overnight build records.\n\n"
        "Generated by `tools/sync_docs.py`; edit the originals, not these copies. Left out on purpose: draft messages "
        "to people, verbatim transcriptions of City documents, code snapshots.\n",
        encoding="utf-8",
    )
    print(f"docs/: {total} files copied")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
