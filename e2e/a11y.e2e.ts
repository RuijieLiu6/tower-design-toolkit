// axe-core WCAG 2.1 A/AA checks on every screen (backlog item 16). Fails on serious or critical violations; minor and
// moderate ones are written to the report for follow-up. The 3D canvas itself is not checkable by axe.
import AxeBuilder from '@axe-core/playwright'
import { expect, test, type Page } from '@playwright/test'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPORT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '04 Tool Plan', 'overnight', 'a11y', 'axe-report.md')
type Row = { id: string; impact: string; help: string; nodes: number; targets: string[] }
const STORE = REPORT.replace(/\.md$/, '.json')

/** Results per screen live on disk: a failing test restarts the worker, which would lose them in memory. */
function record(screen: string, rows: Row[]) {
  mkdirSync(dirname(REPORT), { recursive: true })
  const all: Record<string, Row[]> = existsSync(STORE) ? JSON.parse(readFileSync(STORE, 'utf8')) : {}
  all[screen] = rows
  writeFileSync(STORE, JSON.stringify(all, null, 1))
  const lines = Object.entries(all).flatMap(([sc, rs]) => rs.length ? rs.map((f) => `| ${sc} | ${f.impact} | \`${f.id}\` | ${f.help} | ${f.nodes} | ${f.targets.map((t) => `\`${t.replace(/\|/g, '\\|')}\``).join('<br>')} |`) : [`| ${sc} | — | — | No violations | 0 | |`])
  writeFileSync(REPORT, [
    '# axe accessibility report (WCAG 2.1 A/AA)',
    '',
    'Generated by tower-studio/e2e/a11y.e2e.ts with axe-core 4.13.0 in Chrome Headless Shell 153 (Playwright 1.63.0). Serious and critical violations fail the test; minor and moderate ones are listed for follow-up. The 3D canvas content is not checkable by axe.',
    '',
    '| Screen | Impact | Rule | What it means | Elements | First targets |',
    '|---|---|---|---|---|---|',
    ...lines,
    '',
  ].join('\n'))
}

async function scan(page: Page, screen: string) {
  const r = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()
  record(screen, r.violations.map((v) => ({ id: v.id, impact: v.impact ?? 'unknown', help: v.help, nodes: v.nodes.length, targets: v.nodes.slice(0, 4).map((n) => n.target.join(' ')) })))
  return r.violations.filter((v) => v.impact === 'serious' || v.impact === 'critical')
}

async function open(page: Page, hash: string) {
  await page.addInitScript(() => { try { localStorage.setItem('ts.landing.skip', '0') } catch { /* ignore */ } })
  await page.goto(`/${hash}`)
  await page.waitForLoadState('networkidle')
  // The app has mounted (a dev-server reload mid-run would otherwise leave an empty page).
  await page.waitForSelector('#root > *', { timeout: 30_000 })
  await page.waitForTimeout(1500)
}

async function guided(p: Page, stage: '1' | '2' | '3' = '1') {
  await open(p, '#/guided')
  await p.getByRole('button', { name: 'Start designing' }).click().catch(() => {})
  if (stage !== '1') await p.keyboard.press(stage)
  await p.waitForTimeout(1200)
}

/**
 * Shows a node's results. Switching a node on in the bottom bar also selects it; a node that is already on is picked
 * in the results panel's "Show results for" list (clicking its icon would switch it off).
 */
async function showNode(p: Page, name: string) {
  const sw = p.getByRole('switch', { name: `Use ${name}`, exact: true })
  await sw.waitFor({ timeout: 20_000 })
  if ((await sw.getAttribute('aria-checked')) === 'false') await sw.click()
  else {
    await p.getByRole('tab', { name: /Results/ }).click().catch(() => {})
    await p.getByLabel('Show results for').selectOption({ label: name })
  }
  await p.getByRole('tab', { name: /Results/ }).click().catch(() => {})
}

/** Opens the guided app and shows a node's results. */
async function node(p: Page, name: string, stage: '1' | '2' = '1') {
  await guided(p, stage)
  await showNode(p, name)
  await p.waitForTimeout(800)
}

