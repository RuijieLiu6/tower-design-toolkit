// AI-use and provenance log (research P07-M07, round 4): who or what made each element, what each person decided,
// and the IPTC digital-source-type term for each image. The board appendix lists AI use, sources, module names and
// licences only, never people. Stripping identity from exported files belongs to the board export (backlog item 5).

export type Involvement = 'capture' | 'capture-montage' | 'none' | 'assist' | 'generative-edit' | 'composite' | 'generated'
export type ElementKind = 'image' | 'text' | 'drawing' | 'result'
export type Decider = 'person' | 'code' | 'ai-proposed-person-accepted' | 'ai'

/** ai_involvement to IPTC digital source type (P07-M07 r4 mapping; IPTC NewsCodes, research P07-S38). The term choice per level is the team's. */
export const IPTC: Record<Involvement, { label: string; term: string; generative: boolean; visible: string }> = {
  capture: { label: 'Photo or scan, no AI', term: 'digitalCapture', generative: false, visible: 'Photo' },
  'capture-montage': { label: 'Montage of captures, no AI', term: 'compositeCapture', generative: false, visible: 'Photo montage' },
  none: { label: 'Made by a person with non-AI digital tools (render, drawing)', term: 'digitalCreation', generative: false, visible: 'Digital drawing, no AI' },
  assist: { label: 'Non-generative AI assist (denoise, upscale, enhance)', term: 'algorithmicallyEnhanced', generative: false, visible: 'AI-enhanced (non-generative)' },
  'generative-edit': { label: 'Generative edit of a human-made image (fill, extend, restyle)', term: 'compositeWithTrainedAlgorithmicMedia', generative: true, visible: 'Edited with generative AI' },
  composite: { label: 'Composite with AI-generated elements', term: 'compositeSynthetic', generative: true, visible: 'Composite with AI-generated elements' },
  generated: { label: 'Generated by AI from a prompt', term: 'trainedAlgorithmicMedia', generative: true, visible: 'AI-generated' },
}
export const IPTC_BASE = 'http://cv.iptc.org/newscodes/digitalsourcetype/'

export const DECIDER_LABEL: Record<Decider, string> = {
  person: 'A person decided',
  code: 'Deterministic code (a node)',
  'ai-proposed-person-accepted': 'AI proposed, a person accepted',
  ai: 'AI decided (needs a person to check)',
}

export interface ProvEntry {
  id: string
  element: string
  kind: ElementKind
  involvement: Involvement
  /** Tool and version, e.g. "Codex CLI 0.163 + gpt-image-2". */
  tool: string
  /** The tool itself generates content (from the tool log), to catch an understated involvement level. */
  toolGenerative: boolean
  date: string
  humanContribution: string
  decidedBy: Decider
  /** Text that touches culture or the Nations, drafted with AI, needs a named reviewer (kept off exports). */
  cultural: boolean
  reviewer: string
  /** Licence or terms of use of the image or tool output. */
  licence: string
  sourceIds: string
}

export interface ProvIssue { id: string; entry: string; text: string }

/** P07-M07 metrics, one line per problem. */
export function provenanceIssues(list: ProvEntry[]): ProvIssue[] {
  const out: ProvIssue[] = []
  for (const e of list) {
    const name = e.element || '(unnamed element)'
    if (!e.humanContribution.trim()) out.push({ id: 'contribution', entry: e.id, text: `${name}: say what a person contributed.` })
    if (e.decidedBy === 'ai') out.push({ id: 'decided', entry: e.id, text: `${name}: a person must decide or accept it.` })
    const involved = e.involvement !== 'capture' && e.involvement !== 'capture-montage' && e.involvement !== 'none'
    if (e.toolGenerative && !IPTC[e.involvement].generative) out.push({ id: 'understated', entry: e.id, text: `${name}: the tool is generative but the level says "${IPTC[e.involvement].label}". When unsure, declare more AI use.` })
    if (e.kind === 'text' && e.cultural && (involved || e.toolGenerative) && !e.reviewer.trim()) out.push({ id: 'reviewer', entry: e.id, text: `${name}: AI-drafted cultural text needs a named human reviewer.` })
    if (e.kind === 'image' && (involved || e.toolGenerative) && !e.licence.trim()) out.push({ id: 'licence', entry: e.id, text: `${name}: record the AI tool's terms or licence (the organizer may ask).` })
    if (e.kind === 'result' && !e.sourceIds.trim()) out.push({ id: 'source', entry: e.id, text: `${name}: a result without a source cannot be checked.` })
  }
  return out
}

/** Board appendix: AI use, sources, module names and licences only. No people, handles or reviewer names. */
export function boardAppendix(list: ProvEntry[], modules: { name: string; licence: string }[]): string {
  const lines: string[] = ['AI use and sources']
  const ai = list.filter((e) => e.involvement !== 'capture' && e.involvement !== 'capture-montage' && e.involvement !== 'none' || e.toolGenerative)
  if (!ai.length) lines.push('- No AI-generated or AI-edited elements are declared.')
  for (const e of ai) {
    const lvl = IPTC[e.involvement]
    lines.push(`- ${e.element}: ${lvl.visible.toLowerCase()} (IPTC ${lvl.term})${e.tool ? `, tool: ${e.tool}` : ''}${e.date ? `, ${e.date}` : ''}.`)
  }
  const sources = [...new Set(list.flatMap((e) => e.sourceIds.split(/[;,]/).map((s) => s.trim()).filter(Boolean)))]
  if (sources.length) lines.push('', 'Sources', ...sources.map((s) => `- ${s}`))
  if (modules.length) lines.push('', 'Software modules and licences', ...modules.map((m) => `- ${m.name}: ${m.licence}`))
  return lines.join('\n')
}

