// Source of the service worker (sw.js) that pwa.plugin.ts writes into every build (backlog item 30). A plain string
// builder, so sw.test.ts can run the worker against a fake cache and network. `never` is precache.ts NEVER_CACHE.

/** The service worker: precache at install; afterwards the page from the network when online, else from the cache. */
export function serviceWorker(cache: string, files: string[], never: RegExp[]): string {
  return `// Tower Design Toolkit offline cache (generated by pwa.plugin.ts at build time; do not edit).
const CACHE = ${JSON.stringify(cache)}
const PRECACHE = ${JSON.stringify(files)}
// Never stored: the private competition model and the live evaluation run.
const NEVER = [${never.map(String).join(', ')}]
const scope = new URL(self.registration.scope)
// Servers may send "Vary: Origin" (Vite does); module scripts are requested with an Origin header and the precache
// was not, so lookups ignore Vary or they would miss every script offline.
const LOOKUP = { ignoreSearch: true, ignoreVary: true }

self.addEventListener('install', (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE))))
self.addEventListener('activate', (e) => e.waitUntil(
  caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('tower-studio-') && k !== CACHE).map((k) => caches.delete(k)))),
))
self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return
  const path = url.pathname.slice(scope.pathname.length)
  if (NEVER.some((r) => r.test(path)) || req.cache === 'no-store') return
  if (req.mode === 'navigate') {
    // The page: fresh when online (so an update shows), the cached copy when offline.
    e.respondWith(fetch(req).then((res) => {
      if (res.ok && (res.headers.get('content-type') || '').includes('text/html')) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put('index.html', copy)) }
      return res
    }).catch(() => caches.match('index.html', LOOKUP).then((hit) => hit || Response.error())))
    return
  }
  // Built files have content hashes in their names: the cached copy is the right one. Anything else (the massing
  // importers, a file added later) is kept after its first download.
  e.respondWith(caches.match(req, LOOKUP).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok && res.type === 'basic') { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)) }
    return res
  })))
})
`
}
